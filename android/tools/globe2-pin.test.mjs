import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { KT, OUT, PIN } from './globe2-pin.mjs';

// Why: the native flat globe's camera, picking and cost tests compare against numbers exported from ONE pinned web
// commit (tools/globe2-pin.mjs). If the tool, the generated Kotlin constants and the goldens disagree about that pin,
// the JVM tests would prove parity with a web that no longer exists. These run without the web repo; the drift
// re-export against the real pin is the local gate step `node tools/globe2-pin.mjs --source <SHARDKEEP-globe> --check`
// (the pin is on no remote, so CI cannot run it).
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sha256 = b => createHash('sha256').update(b).digest('hex');

test('the generated constants, the goldens and the tool name one pin, and the goldens come from this tool', () => {
  assert.match(PIN, /^[0-9a-f]{40}$/);
  const kt = fs.readFileSync(path.join(ROOT, KT), 'utf8');
  assert.ok(kt.includes(`const val PIN: String = "${PIN}"`), 'GlobeV2Pin.kt is generated at the tool\'s pin');
  assert.ok(kt.startsWith('// GENERATED by tools/globe2-pin.mjs'), 'GlobeV2Pin.kt is never hand-written');
  const generator = sha256(fs.readFileSync(path.join(ROOT, 'tools/globe2-pin.mjs')));
  for (const name of ['camera.json', 'picking.json', 'islands.json']) {
    const g = JSON.parse(fs.readFileSync(path.join(ROOT, OUT, name), 'utf8'));
    assert.equal(g.pin, PIN, `${name} is exported at the pin`);
    assert.equal(g.generator, generator, `${name} was written by this version of the tool (re-run it after editing the tool)`);
  }
});

test('the goldens carry what the JVM tests need, at full size', () => {
  const cam = JSON.parse(fs.readFileSync(path.join(ROOT, OUT, 'camera.json'), 'utf8'));
  assert.equal(cam.cases.length, 24); assert.equal(cam.grabs.length, 60); assert.equal(cam.fits.length, 30);
  assert.ok(cam.grabs.every(g => !('w' in g)), 'no key collides with "W" (libGDX JsonValue matches keys case-insensitively)');
  const pick = JSON.parse(fs.readFileSync(path.join(ROOT, OUT, 'picking.json'), 'utf8'));
  assert.equal(pick.picks.length, 5000); assert.equal(pick.geoms.length, 8);
  for (const [file, sha] of Object.entries(pick.masks)) assert.equal(sha256(fs.readFileSync(path.join(ROOT, OUT, file))), sha, `${file} is the copy the goldens were computed on`);
  const isles = JSON.parse(fs.readFileSync(path.join(ROOT, OUT, 'islands.json'), 'utf8'));
  assert.equal(isles.chains.reduce((n, c) => n + c.islands.length, 0), 32, 'the 32 exploration islands');
  for (const s of ['globe-flat', 'globe-isles', 'globe-fx']) for (const k of ['vs', 'fs'])
    assert.ok(fs.readFileSync(path.join(ROOT, OUT, 'shaders', `${s}.${k}.glsl`), 'utf8').startsWith('#version 300 es\n'), `${s}.${k}`);
});
