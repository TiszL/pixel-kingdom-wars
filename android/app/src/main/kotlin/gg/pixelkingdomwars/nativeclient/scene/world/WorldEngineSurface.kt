/**
 * Whether the World tab runs the GL30 engines (N1 flat globe + N2 overview realm maps) — lead integration, D-171; in
 * every build type since N5 (D-175/D-NEXT: the world content is bundled in every APK, release included).
 *
 * Admitted only when all hold, in [refusal]'s order: the debug launch extra `worldLegacy` is not set (the owner's
 * side-by-side with the legacy globe, RG-1; debug builds only), the device reports OpenGL ES 3.0+, the build carries the
 * world bundle (`app/src/main/assets/world`, generated by `tools/world-debug-content.mjs`), the server has not switched
 * the new world off ([WorldV2Switch], the last `worldV2` read), and this device's crash record does not stop the realm
 * map ([HangMemory.stopReason]). Nothing here depends on the build type. The engine guard (`WorldEngineGuard.decide`, on
 * the GL thread) still refuses a non-SwiftShader emulator and any context without GL30; every refusal or failure hands
 * the tab back to the legacy globe.
 */
object WorldEngineAdmission {
    @Volatile private var bundle: Boolean? = null

    /** Null when admitted, else the reason the legacy globe runs (logged once per decision by the caller). The switch and
     *  the crash record are read afresh on every call; only the bundle probe is kept (an APK's assets never change). */
    fun refusal(context: Context): String? {
        val gles = context.getSystemService(ActivityManager::class.java)?.deviceConfigurationInfo?.reqGlEsVersion ?: 0
        val present = bundle ?: runCatching { context.assets.open(WORLD_CONTENT).use { true } }.getOrDefault(false).also { bundle = it }
        return refusal(WorldEngineFlags.legacyWorld, gles, present, WorldV2Switch.of(context).enabled,
            HangMemory.stopReason(HangRecordStore.of(context).load(), System.currentTimeMillis()))
    }

    /** The rule itself: null admits the GL30 world. */
    fun refusal(legacyRequested: Boolean, gles: Int, bundle: Boolean, worldV2: Boolean, hangStop: String?): String? = when {
        legacyRequested -> "the legacy globe was requested (worldLegacy)"
        gles < GLES_3_0 -> "OpenGL ES 0x${Integer.toHexString(gles)} < 3.0"
        !bundle -> "this build carries no world content"
        !worldV2 -> "the new world is switched off by the server (worldV2)"
        hangStop != null -> "the realm map is stopped on this device: $hangStop"
        else -> null
    }

    const val GLES_3_0 = 0x30000
    const val WORLD_CONTENT = "world/${AssetWorldFiles.CONTENT}"
}

/**
 * The client pack's globe files for [GlobeContent]: the verified world overview directory (masks, island effects) and
 * the exploration chains' art from their own verified groups (`chain-<id>`, acquired through the World tab's
 * [GlobeAssetSource]; each read takes a lease and releases it once the bytes are in memory). Both come from
 * `WorldContent`, which checked every file against the admitted render catalogue's pins before activation, so no outer
 * sha256 is repeated here ([GlobeContent] documents the same). Chain reads stop after [chainBudgetMs] in total (a slow
 * network): the globe then loads without the exploration islands instead of not at all. Decode threads only.
 */
class WorldPackFiles(private val overview: File, private val chains: GlobeAssetSource?, private val chainBudgetMs: Long = CHAIN_BUDGET_MS,
                     private val log: (String) -> Unit = {}) : GlobeFiles {
    @Volatile private var deadlineNs = 0L
    private val watchdog = AtomicBoolean(false)

    override fun read(path: String): ByteArray? {
        if (!path.startsWith(GlobeContent.CHAIN_DIR)) return file(overview, path)
        val source = chains ?: return null
        val name = path.removePrefix(GlobeContent.CHAIN_DIR)
        val id = name.substringBefore("-detail")
        if (id.isEmpty() || id == name || !id.matches(CHAIN_ID)) return null
        if (deadlineNs == 0L) deadlineNs = System.nanoTime() + chainBudgetMs * 1_000_000
        if (System.nanoTime() > deadlineNs) return null
        armWatchdog(source)
        return try {
            source.acquire("chain-$id") {}.use { lease -> file(lease.directory.file(), path) }
        } catch (e: Exception) {
            log("[world-engine] chain $id art unavailable: ${e.message ?: e.javaClass.simpleName}")
            null
        }
    }

    override fun expectedSha256(path: String): String? = null

    /** One daemon thread per load: after the budget it cancels a stalled group download (never joined). */
    private fun armWatchdog(source: GlobeAssetSource) {
        if (!watchdog.compareAndSet(false, true)) return
        Thread({
            try { Thread.sleep(chainBudgetMs) } catch (_: InterruptedException) { return@Thread }
            source.cancelPending()
        }, "world-chain-watchdog").apply { isDaemon = true }.start()
    }

    private fun file(root: File, path: String): ByteArray? {
        val f = File(root, path)
        val canonical = runCatching { f.canonicalFile }.getOrNull() ?: return null
        if (!canonical.path.startsWith(root.canonicalPath + File.separator)) return null
        return if (canonical.isFile) canonical.readBytes() else null
    }

    companion object {
        /** Lead bound (not a web number): the first World entry downloads 7 small chain groups; beyond this the globe
         *  loads without its exploration islands and the legacy globe keeps them. */
        const val CHAIN_BUDGET_MS = 20_000L
        private val CHAIN_ID = Regex("[a-z][a-z0-9-]*")
    }
}

/** The realm map's game numbers: only the sections the realm core and its N3 lanes read (the core's four, plus BASES'
 *  `DecorGame`: mines, build caps, source scales, footprints, ware presentation) of the admitted catalogue are
 *  serialised (tens of KB), never the whole catalogue on the UI thread. */
fun realmCatalogueNumbers(catalogue: JsonObject?): RealmEngineWiring.CatalogueNumbers? {
    val constants = catalogue?.get("constants") as? JsonObject ?: return null
    val subset = JsonObject(constants.filterKeys { it in REALM_CONSTANTS })
    return runCatching { RealmEngineWiring.fromCatalogue(JsonObject(mapOf("constants" to subset)).toString()) }.getOrNull()
}

private val REALM_CONSTANTS = setOf("CAMPAIGN", "CAMPAIGN_LAYOUT", "BASE_GROUND_WORLD_GEOMETRY", "GRID",
    "MINING", "BUILD_COUNT_CAP_BY_KEEP", "ART_V2", "STRUCTURES", "DEFENSES", "WARE_WORLD_PRESENTATION")

/**
 * NU's [WorldEngineSurface] over the GL30 world host (lead integration). [inputs] builds the host's inputs from the
 * verified overview directory the HUD hands over (UI thread; null refuses the engine, and the HUD falls back to the
 * legacy globe). The fragment tag is `world-engine-<dir>`, never the legacy `fantasy-globe-<dir>`, so a fallback swap
 * cannot collide with the legacy surface's own fragment.
 */
class Gl30WorldEngineSurface(private val inputs: (art: File, context: Context) -> WorldHostInputs?) : WorldEngineSurface {
    @Composable override fun Content(art: File, bridge: WorldHudBridge, modifier: Modifier) {
        val activity = requireNotNull(LocalActivity.current as? FragmentActivity)
        val tag = "world-engine-${art.name}"
        val id = remember { View.generateViewId() }
        val fragment = remember(tag) { WorldEngineFragment() }
        var status by remember { mutableStateOf<String?>(null) }
        val remove: () -> Unit = remember(fragment) { {
            if (!activity.isDestroyed && !activity.supportFragmentManager.isDestroyed && fragment.isAdded)
                activity.supportFragmentManager.beginTransaction().remove(fragment).commitNowAllowingStateLoss()
        } }
        LaunchedEffect(bridge, fragment) { snapshotFlow { bridge.globeLayout }.collect { fragment.layout(it) } }
        // The globe's postcard (ScenePostcards.world): 1.5 s after the globe is ready, then every 10 s while the map is up.
        val lifecycle = androidx.lifecycle.compose.LocalLifecycleOwner.current.lifecycle
        LaunchedEffect(bridge, fragment, tag) {
            snapshotFlow { bridge.ready }.first { it }
            kotlinx.coroutines.delay(gg.pixelkingdomwars.nativeclient.scene.POSTCARD_SETTLE_MS)
            while (true) {
                if (lifecycle.currentState.isAtLeast(androidx.lifecycle.Lifecycle.State.RESUMED))
                    gg.pixelkingdomwars.nativeclient.scene.ScenePostcards.captureWorld(fragment, tag)
                kotlinx.coroutines.delay(gg.pixelkingdomwars.nativeclient.scene.POSTCARD_PROACTIVE_EVERY_MS)
            }
        }
        LaunchedEffect(bridge, fragment) { snapshotFlow { bridge.realmFocusOffset }.collect { fragment.focus(it.first, it.second) } }
        Box(modifier.then(FragmentTeardownElement(remove))) {
            AndroidView(modifier = Modifier.fillMaxSize(), factory = { context -> FrameLayout(context).also { container ->
                container.withoutSceneInputFocus()
                container.id = id
                fragment.bind(bridge) { status = it }
                fragment.inputs = { inputs(art, context) }
                container.doOnAttach { if (!fragment.isAdded && !activity.supportFragmentManager.isStateSaved) activity.supportFragmentManager.beginTransaction().add(id, fragment, tag).commitNow() }
            } })
            // Debug readout for the owner's Seeker session (D-171): engine, mode, presented fps, ladder level, realm status.
            // Debug and candidate builds only: the host sends no status line where [WorldLog] is off (release).
            status?.let { line ->
                Text(line, color = Color(0xFFE8E0C8), fontSize = 10.sp, lineHeight = 11.sp,
                    modifier = Modifier.align(Alignment.BottomStart).windowInsetsPadding(WindowInsets.safeDrawing).padding(start = 4.dp, bottom = 2.dp)
                        .background(Color(0x99000000)).padding(horizontal = 3.dp))
            }
        }
        DisposableEffect(fragment) { onDispose { fragment.unbind(); remove() } }
    }
}

/** Field report 2026-10-06 (MAP → back showed one black frame with the realm labels and the world HUD): what lies under the
 *  world's GL surface — the globe's postcard when it was taken at this size for this content, else the globe's own sky
 *  (never the #100E14 window). Invisible while the surface is up (a SurfaceView punches through what is drawn below it). */
@Composable internal fun WorldBacking(contentTag: String?) {
    androidx.compose.foundation.layout.BoxWithConstraints(Modifier.fillMaxSize().background(gg.pixelkingdomwars.nativeclient.ui.world.WORLD_SKY)) {
        // A null tag (the surface already left with its art) accepts the globe picture of this size it last took.
        val card = gg.pixelkingdomwars.nativeclient.scene.ScenePostcards.world.shown?.takeIf { postcard ->
            gg.pixelkingdomwars.nativeclient.scene.worldPostcardAdmitted(postcard.key, postcard.savedAtMs, contentTag ?: postcard.key.contentTag,
                constraints.maxWidth, constraints.maxHeight, System.currentTimeMillis()) }
        if (card != null) androidx.compose.foundation.Image(card.image, contentDescription = null, modifier = Modifier.fillMaxSize(),
            contentScale = androidx.compose.ui.layout.ContentScale.FillBounds, filterQuality = androidx.compose.ui.graphics.FilterQuality.Low)
    }
}

/**
 * The fragment that owns the GL30 world surface for one World entry: [WorldEngineHost] on `WorldGraphics` (robust ES 3
 * context, frame pacer), with the surface buffer fixed at the engine's dpr (plan §5.5). Every GL → UI callback is posted
 * to the main looper and dropped once this view is gone (epoch guard); frame notices are conflated to one post.
 */
class WorldEngineFragment : WorldApplicationFragment() {
    var inputs: (() -> WorldHostInputs?)? = null
    var host: WorldEngineHost? = null; private set
    private var bridge: WorldHudBridge? = null
    private var onStatus: (String?) -> Unit = {}
    private var epoch: Any? = null
    private var pendingLayout: GlobeHudLayout? = null
    private var pendingFocus = 0f to 0f
    private val main = Handler(Looper.getMainLooper())
    private val framePosted = AtomicBoolean(false)
    private val frameRunnable = Runnable { framePosted.set(false); if (epoch != null) bridge?.framePublished() }
    private var thermal: android.os.PowerManager.OnThermalStatusChangedListener? = null

    fun bind(bridge: WorldHudBridge, onStatus: (String?) -> Unit) { this.bridge = bridge; this.onStatus = onStatus }
    fun unbind() { epoch = null; bridge?.controls = null; bridge = null; onStatus = {} }
    fun layout(layout: GlobeHudLayout?) { pendingLayout = layout; host?.setLayout(layout) }
    fun focus(dx: Float, dy: Float) { pendingFocus = dx to dy; host?.setFocus(dx, dy) }

    override fun onCreateView(inflater: LayoutInflater, container: ViewGroup?, state: Bundle?): View {
        val log: (String) -> Unit = WorldLog.line
        // Null inputs: a fragment AndroidX rebuilt from saved state that discardRestoredGlSurfaces missed. An empty frame,
        // never a throw in Activity.onStart (that crashed the app on a theme flip or a process restore).
        val made = inputs?.invoke()
        val b = bridge
        if (made == null || b == null) {
            // Refused before any GL exists: the HUD's fallback shows the legacy globe (this view stays an empty frame).
            log("[world-engine] FALLBACK to the legacy globe: the world engine inputs are unavailable")
            b?.let { bridge -> main.post { bridge.failure = "The world engine inputs are unavailable" } }
            return FrameLayout(requireContext())
        }
        val token = Any(); epoch = token
        fun post(action: (WorldHudBridge) -> Unit) { main.post { if (epoch === token) bridge?.let(action) } }
        val callbacks = object : WorldHostCallbacks {
            override fun ready() = post { it.ready = true }
            override fun failed(reason: String) = post { it.failure = reason }
            override fun framePublished() { if (framePosted.compareAndSet(false, true)) main.post(frameRunnable) }
            override fun event(event: WorldHudEvent) = post { it.emit(event) }
            override fun mapRealms(ids: Set<String>) = post { it.mapRealms = ids }
            override fun readiness(realmId: String, value: Float) = post { it.diveReadiness = realmId to value }
            override fun realmGrid(info: RealmGridInfo?) = post { it.realmGrid = info }
            override fun loading(value: Float) = post { it.loading = value }
            override fun status(line: String) { main.post { if (epoch === token) onStatus(line) } }
            override fun bandGate(held: Boolean, band: Int, progress: Double) = post { it.bandGate = BandGateCue(held, band, progress) }
            override fun detailRealms(ids: Set<String>) = post { it.detailRealms = ids }
        }
        return try {
            val h = WorldEngineHost(made, { worldGraphics }, callbacks, File(requireContext().noBackupFilesDir, "world-programs"),
                BuildConfig.VERSION_CODE.toLong(), log)
            host = h
            b.controls = h.controls; b.exchange = h.exchange; b.dpr = h.dpr.toFloat()
            h.setLayout(pendingLayout); h.setFocus(pendingFocus.first, pendingFocus.second)
            val config = AndroidApplicationConfiguration().apply {
                useAccelerometer = false; useCompass = false; useGyroscope = false; useImmersiveMode = false; numSamples = 0; useGL30 = true
            }
            val view = initializeWorldView(h, config, WorldContextFactory(3, log), FramePacer(requireContext(), 60, log)).withoutSceneInputFocus()
            view.addOnLayoutChangeListener { v, l, t, r, bottom, _, _, _, _ ->
                h.viewSize(r - l, bottom - t) { w, hh -> (v as? SurfaceView)?.holder?.setFixedSize(w, hh) }
            }
            view.doOnAttach { mounted -> mounted.post { if (mounted.isAttachedToWindow) mounted.rootView.postInvalidateOnAnimation() } }
            watchThermal(h)
            view
        } catch (e: Exception) {
            epoch = null; host = null
            runCatching { made.resources?.close() }
            log("[world-engine] FALLBACK to the legacy globe: ${e.message ?: e.javaClass.simpleName}")
            main.post { b.failure = "The world engine could not start: ${e.message ?: e.javaClass.simpleName}" }
            FrameLayout(requireContext())
        }
    }

    /** The ladder's thermal floor (plan §5.4): status changes and the 10 s headroom forecast, on the GL thread. */
    private fun watchThermal(h: WorldEngineHost) {
        if (android.os.Build.VERSION.SDK_INT < android.os.Build.VERSION_CODES.Q) return
        val power = requireContext().getSystemService(android.os.PowerManager::class.java) ?: return
        fun headroom(): Double = if (android.os.Build.VERSION.SDK_INT >= android.os.Build.VERSION_CODES.R) power.getThermalHeadroom(10).toDouble() else Double.NaN
        val listener = android.os.PowerManager.OnThermalStatusChangedListener { status -> h.thermal(status, headroom()) }
        runCatching { power.addThermalStatusListener(requireContext().mainExecutor, listener); thermal = listener; h.thermal(power.currentThermalStatus, headroom()) }
    }

    override fun onDestroyView() {
        thermal?.let { l -> if (android.os.Build.VERSION.SDK_INT >= android.os.Build.VERSION_CODES.Q) runCatching { context?.getSystemService(android.os.PowerManager::class.java)?.removeThermalStatusListener(l) } }
        thermal = null
        // P0 (2026-09-26): the HUD bridge outlives this view, and its controls and exchange reach the host (and through it
        // whatever the host still holds); only this host's are dropped, never a newer view's
        host?.let { h -> bridge?.let { b -> if (b.controls === h.controls) b.controls = null; if (b.exchange === h.exchange) b.exchange = null } }
        // P0: an activity recreation (a theme, font-size or locale change) never reaches libGDX's destroy, so nothing
        // disposed this host and its threads kept its world alive; after a normal leave's dispose this does nothing
        host?.releaseWithoutGl()
        epoch = null; host = null
        main.removeCallbacks(frameRunnable)
        super.onDestroyView()
        if (worldGraphics != null) WorldGdxStatics.clearGl30()
    }
}

/**
 * The World tab's inputs for [WorldEngineHost] (UI thread, D-171 admission): the bundled world content, the client
 * pack's globe files ([WorldPackFiles]) under a scene lease on the verified overview directory, the legacy island model,
 * the realm map's catalogue numbers and the device's crash record ([HangRecordStore]). Null when the overview directory
 * is not a verified generation (the HUD then falls back to the legacy globe, which refuses the same directory).
 */
fun worldHostInputs(context: Context, overview: File, chains: GlobeAssetSource?, art: GlobeArt?, catalogue: JsonObject?, log: (String) -> Unit): WorldHostInputs? {
    val root = File(context.noBackupFilesDir, storageNamespace(BuildConfig.API_ORIGIN, "world-content"))
    val owner = overview.parentFile ?: return null
    if (!(owner == root || (owner.parentFile == File(root, "groups") && owner.name == "overview"))) { log("[world-engine] overview escapes its verified cache"); return null }
    val lease: ContentLease = runCatching { SceneContentLeases.acquire(owner, overview) }.getOrElse { log("[world-engine] overview lease: ${it.message}"); return null }
    val numbers = realmCatalogueNumbers(catalogue)
    if (numbers == null) log("[world-engine] the catalogue has no realm-map numbers: realm maps are off")
    return WorldHostInputs(context.assets, AssetWorldFiles(context.assets), WorldPackFiles(overview, chains, log = log), art, numbers,
        context.resources.displayMetrics.density.toDouble(), lease, HangRecordStore.of(context))
}

/**
 * The World tab's engine choice (PkwApp's one-liner): the GL30 surface when [WorldEngineAdmission] admits it, else null
 * (the legacy globe, unchanged). Decided once per World view model each time the World tab is composed, so a `worldV2`
 * switch-off or a crash record read meanwhile takes effect at the next World visit or app start, never mid-visit. The
 * reason is logged under `PKWWorldGL` ([WorldLog]: debug and candidate builds; release prints nothing).
 */
@Composable fun rememberWorldEngine(model: gg.pixelkingdomwars.nativeclient.ui.world.WorldViewModel, catalogue: () -> JsonObject?): WorldEngineSurface? {
    val context = androidx.compose.ui.platform.LocalContext.current
    return remember(model) {
        val log: (String) -> Unit = WorldLog.line
        val refusal = WorldEngineAdmission.refusal(context)
        if (refusal != null) { log("[world-engine] legacy globe: $refusal"); null }
        else {
            log("[world-engine] admitted: GL30 globe + realm maps (bundled world content)")
            Gl30WorldEngineSurface { art, ctx ->
                val spec = runCatching { model.artSpec }.onFailure { log("[world-engine] no exploration islands: ${it.message}") }.getOrNull()
                worldHostInputs(ctx, art, model.state.value.artSource, spec, catalogue(), log)
            }
        }
    }
}
