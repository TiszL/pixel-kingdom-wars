/**
 * Deterministic binary-alpha hand sprites for the in-world KEEP clock.
 *
 * The game never asks Canvas/WebGL to draw a rotated vector. This generator
 * rasterises all sixty minute positions up front with integer Bresenham lines,
 * packs each 17x17 mask into bits, and emits the tiny data-only module consumed
 * by `game/world/keepClock.ts`.
 */
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';
import { writeFile } from 'node:fs/promises';

export const KEEP_CLOCK_HAND_CELL_PX = 17;
export const KEEP_CLOCK_HAND_FRAME_COUNT = 60;
export const KEEP_CLOCK_MINUTE_RADIUS_PX = 7;
export const KEEP_CLOCK_HOUR_RADIUS_PX = 5;

export interface KeepClockHandMasks {
  hour: Uint8Array;
  minute: Uint8Array;
}

const FRAME_PIXELS = KEEP_CLOCK_HAND_CELL_PX * KEEP_CLOCK_HAND_CELL_PX;
export const KEEP_CLOCK_HAND_BYTES_PER_FRAME = Math.ceil(FRAME_PIXELS / 8);

function setPixel(mask: Uint8Array, frame: number, x: number, y: number): void {
  if (x < 0 || y < 0 || x >= KEEP_CLOCK_HAND_CELL_PX || y >= KEEP_CLOCK_HAND_CELL_PX) return;
  const bit = y * KEEP_CLOCK_HAND_CELL_PX + x;
  const byte = frame * KEEP_CLOCK_HAND_BYTES_PER_FRAME + (bit >> 3);
  mask[byte] = mask[byte]! | (1 << (bit & 7));
}

function integerLine(x0: number, y0: number, x1: number, y1: number): Array<readonly [number, number]> {
  const points: Array<readonly [number, number]> = [];
  let x = x0;
  let y = y0;
  const dx = Math.abs(x1 - x0);
  const sx = x0 < x1 ? 1 : -1;
  const dy = -Math.abs(y1 - y0);
  const sy = y0 < y1 ? 1 : -1;
  let error = dx + dy;
  for (;;) {
    points.push([x, y]);
    if (x === x1 && y === y1) return points;
    const doubled = error * 2;
    if (doubled >= dy) { error += dy; x += sx; }
    if (doubled <= dx) { error += dx; y += sy; }
  }
}

function handMask(radius: number, wide: boolean): Uint8Array {
  const result = new Uint8Array(KEEP_CLOCK_HAND_BYTES_PER_FRAME * KEEP_CLOCK_HAND_FRAME_COUNT);
  const centre = Math.floor(KEEP_CLOCK_HAND_CELL_PX / 2);
  for (let frame = 0; frame < KEEP_CLOCK_HAND_FRAME_COUNT; frame++) {
    const angle = -Math.PI / 2 + frame * Math.PI * 2 / KEEP_CLOCK_HAND_FRAME_COUNT;
    const endX = centre + Math.round(Math.cos(angle) * radius);
    const endY = centre + Math.round(Math.sin(angle) * radius);
    for (const [x, y] of integerLine(centre, centre, endX, endY)) {
      setPixel(result, frame, x, y);
      if (wide) {
        setPixel(result, frame, x - 1, y);
        setPixel(result, frame, x + 1, y);
        setPixel(result, frame, x, y - 1);
        setPixel(result, frame, x, y + 1);
      }
    }
    // Both hands share a square mechanical pin. It remains crisp at every
    // angle and prevents the two independently-coloured masks looking detached.
    for (let y = centre - 1; y <= centre + 1; y++) {
      for (let x = centre - 1; x <= centre + 1; x++) setPixel(result, frame, x, y);
    }
  }
  return result;
}

export function generateKeepClockHandMasks(): KeepClockHandMasks {
  return {
    hour: handMask(KEEP_CLOCK_HOUR_RADIUS_PX, true),
    minute: handMask(KEEP_CLOCK_MINUTE_RADIUS_PX, false),
  };
}

function wrappedBase64(bytes: Uint8Array): string {
  return Buffer.from(bytes).toString('base64').match(/.{1,96}/g)?.join('\n') ?? '';
}

function literal(name: string, bytes: Uint8Array): string {
  const rows = wrappedBase64(bytes).split('\n');
  return `export const ${name} =\n${rows.map((row, index) => (
    `  '${row}'${index === rows.length - 1 ? ';' : ' +'}`
  )).join('\n')}\n`;
}

export function generatedKeepClockHandModule(): string {
  const masks = generateKeepClockHandMasks();
  return `/** GENERATED by scripts/src/keep-clock-hand-sprites.ts. Do not hand-edit. */\n`
    + `export const KEEP_CLOCK_HAND_CELL_PX = ${KEEP_CLOCK_HAND_CELL_PX};\n`
    + `export const KEEP_CLOCK_HAND_FRAME_COUNT = ${KEEP_CLOCK_HAND_FRAME_COUNT};\n`
    + `export const KEEP_CLOCK_HAND_BYTES_PER_FRAME = ${KEEP_CLOCK_HAND_BYTES_PER_FRAME};\n`
    + literal('KEEP_CLOCK_HOUR_MASK_BASE64', masks.hour)
    + literal('KEEP_CLOCK_MINUTE_MASK_BASE64', masks.minute);
}

export const GENERATED_KEEP_CLOCK_HAND_FILE = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../../apps/web/src/game/world/keepClockHands.generated.ts',
);

async function main(): Promise<void> {
  await writeFile(GENERATED_KEEP_CLOCK_HAND_FILE, generatedKeepClockHandModule(), 'utf8');
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await main();
}
