/** D153.22: deterministic Rust projection of the shared Seeker policy. No builds or deployment. */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { PHASE_E_CHARTER_TRANSFER, PHASE_E_DEVNET_TEST, PHASE_E_POLICY, PHASE_E_SEEKER_SALE, PHASE_E_SEEKER_AUCTION, PHASE_E_MINING_PUBLICATION, TOKEN } from '@shardkeep/shared';

export const ECONOMY_CONSTANTS_FILE = resolve(dirname(fileURLToPath(import.meta.url)),
  '../../programs/shardkeep-economy/src/constants.rs');
/** Night 2026-10-06: the projection read only by the `devnet-test` cargo feature of shardkeep-economy. */
export const ECONOMY_DEVNET_TEST_CONSTANTS_FILE = resolve(dirname(fileURLToPath(import.meta.url)),
  '../../programs/shardkeep-economy/src/constants_devnet_test.rs');

type EconomyRow = readonly [string, 'usize' | 'u64' | 'u32' | 'u16' | 'u8' | 'i64', number];

/** The one row table of both projections; only the auction length differs between them. */
function economyRows(overlappingAuctionSec: number): ReadonlyArray<EconomyRow> {
  const p = PHASE_E_POLICY.seekerIsland;
  const a = PHASE_E_SEEKER_AUCTION;
  return [
    ['CHARTER_ROYALTY_BPS', 'u16', PHASE_E_CHARTER_TRANSFER.royaltyBps],
    ['TOTAL_SPOTS', 'usize', p.totalSpots], ['KING_SPOTS', 'usize', p.kingSpots],
    ['REGULAR_SPOTS', 'usize', p.regularSpots], ['REALM_COUNT', 'usize', p.realmCount],
    ['REGULAR_REALM_COUNT', 'usize', a.regularRealmCount],
    ['REGULAR_REALM_COUNT_MIN', 'usize', p.regularRealmCountMin],
    ['REGULAR_REALM_COUNT_MAX', 'usize', p.regularRealmCountMax],
    ['BPS_DENOMINATOR', 'u64', PHASE_E_POLICY.basisPoints], ['PRIZE_BPS', 'u16', a.prizeBps],
    ['OPENING_BID_SKR', 'u64', a.openingBidSkr],
    ['OPERATING_TERM_SEC', 'i64', p.operatingTermSec],
    ['OVERLAPPING_AUCTION_SEC', 'i64', overlappingAuctionSec],
    ['SETTLEMENT_GRACE_SEC', 'i64', a.settlementGraceSec],
    ['MAX_POLICY_PERMIT_TTL_SEC', 'i64', a.maxPolicyPermitTtlSec],
    ['ISSUED_POLICY_PERMIT_TTL_SEC', 'i64', a.issuedPolicyPermitTtlSec],
    ['PERMIT_RECEIPT_RETENTION_SEC', 'i64', a.permitReceiptRetentionSec],
    ['MINING_DAY_SEC','i64',PHASE_E_MINING_PUBLICATION.daySec],
    ['MINING_CLAIM_DELAY_SEC','i64',PHASE_E_MINING_PUBLICATION.claimDelaySec],
    ['MINING_PUBLISHER_MAX_GAP_DAYS','u64',PHASE_E_MINING_PUBLICATION.publisherMaxGapDays],
    ['MINING_GROSS_DAILY_CEILING_BASE_UNITS','u64',PHASE_E_POLICY.mining.grossDailyCeilingKeep * 10 ** TOKEN.decimals],
    ['MINING_FREE_POOL_BPS','u64',PHASE_E_POLICY.mining.freePoolBps],
    ['MINING_DEED_POOL_BPS','u64',PHASE_E_POLICY.mining.deedPoolBps],
    ['MINING_TOKEN_DECIMALS','u8',TOKEN.decimals],
    ['MINING_SPLIT_PERIOD','u64',PHASE_E_MINING_PUBLICATION.splitPeriod],
    ['MINING_SPLIT_PLAYER_UNITS','u64',PHASE_E_MINING_PUBLICATION.splitPlayerUnits],
    ['MINING_SPLIT_RECYCLE_UNITS','u64',PHASE_E_MINING_PUBLICATION.splitRecycleUnits],
    ['MINING_SPLIT_TAX_UNITS','u64',PHASE_E_MINING_PUBLICATION.splitTaxUnits],
    ['REALM_SALE_VERSION', 'u8', PHASE_E_SEEKER_SALE.version],
    ['REALM_SALE_PRICE_LAMPORTS', 'u64', p.permitPriceLamports],
    ['REALM_SALE_DURATION_SEC', 'i64', p.permitDurationSec],
    ['REALM_SALE_SELLER_BPS', 'u16', p.contractSellerBps],
    ['REALM_SALE_DEV_BPS', 'u16', p.contractDevBps],
    ['REALM_SALE_DAILY_QUOTA', 'u8', p.paidContractsPerSpotDayMax],
    ['REALM_SALE_QUOTE_TTL_SEC', 'i64', PHASE_E_SEEKER_SALE.quoteTtlSec],
  ];
}

function render(header: string, rows: ReadonlyArray<EconomyRow>): string {
  return header
    + rows.map(([name, type, value]) => {
      // Shared uses Numbers, so refusing unsafe values is essential before emitting Rust integers.
      if (!Number.isSafeInteger(value) || value < 0 || (type === 'u16' && value > 0xffff) || (type === 'u8' && value > 0xff) || (type === 'u32' && value > 0xffffffff)) {
        throw new Error(`Invalid shared integer for ${name}`);
      }
      return `pub const ${name}: ${type} = ${value};\n`;
    }).join('');
}

export function generateEconomyConstants(): string {
  return render('// GENERATED by scripts/src/generate-economy-constants.ts. Do not hand-edit.\n'
    + '// Source: packages/shared/src/constants.ts, D150, D153.22, D153.62 and D153.88.\n',
  economyRows(PHASE_E_POLICY.seekerIsland.overlappingAuctionSec));
}

export function generateEconomyDevnetTestConstants(): string {
  const overlappingAuctionSec = PHASE_E_DEVNET_TEST.overlappingAuctionSec;
  // auction.rs opens the auction OVERLAPPING_AUCTION_SEC before an operating term starts: it must be a real window inside one term.
  if (!(overlappingAuctionSec > 0 && overlappingAuctionSec <= PHASE_E_POLICY.seekerIsland.operatingTermSec)) {
    throw new Error('PHASE_E_DEVNET_TEST.overlappingAuctionSec must be positive and at most the operating term');
  }
  return render('// GENERATED by scripts/src/generate-economy-constants.ts for the devnet-test cargo feature only. Do not hand-edit.\n'
    + '// Source: packages/shared/src/constants.ts PHASE_E_DEVNET_TEST.overlappingAuctionSec over the shared policy; never the accepted build.\n',
  economyRows(overlappingAuctionSec));
}

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
    throw new Error('Usage: generate-economy-constants.ts [--check]');
  }
  // Both projections are rendered before anything is written, so a refused value leaves neither file half-updated.
  const outputs: ReadonlyArray<readonly [string, string]> = [
    [ECONOMY_CONSTANTS_FILE, generateEconomyConstants()],
    [ECONOMY_DEVNET_TEST_CONSTANTS_FILE, generateEconomyDevnetTestConstants()],
  ];
  for (const [file, expected] of outputs) {
    if (args[0] === '--check') {
      if (await readFile(file, 'utf8') !== expected) {
        throw new Error('Economy Rust constants differ from shared policy; regenerate explicitly');
      }
    } else {
      await mkdir(dirname(file), { recursive: true });
      await writeFile(file, expected, 'utf8');
    }
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) await main();
