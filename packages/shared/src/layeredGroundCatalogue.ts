export function layeredGroundDescriptor(context: BaseVisualContext): LayeredGroundDescriptor {
  if (context.artVersion !== 2 || (context.groundRevision !== 3 && context.groundRevision !== 4)) throw new Error('A layered descriptor requires an explicit layered revision context');
  const row = (context.groundRevision === 4 ? BASE_LAYERED_GROUND_V4 : BASE_LAYERED_GROUND_V3)[context.realmId];
  if (!row) throw new Error(`Layered realm artwork is not published: ${context.realmId}`);
  return row;
}
