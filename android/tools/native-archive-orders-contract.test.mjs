import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

test('archived accepted hero orders survive canonical export and the exact Kotlin decode fixture', () => {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const source = path.resolve(process.env.PKW_NATIVE_SCHEMA_TEST_SOURCE ?? process.env.PKW_NATIVE_SOURCE ?? path.join(root, '.source'));
  const result = spawnSync(process.execPath, ['--import', path.join(source, 'scripts/node_modules/tsx/dist/loader.mjs'), '--input-type=module'], {
    encoding: 'utf8', env: { ...process.env, PKW_TEST_SOURCE: source, PKW_TEST_ROOT: root }, input: `
      import assert from 'node:assert/strict';
      import {readFile} from 'node:fs/promises';
      import {createRequire} from 'node:module';
      import {pathToFileURL} from 'node:url';
      const root = process.env.PKW_TEST_ROOT, source = process.env.PKW_TEST_SOURCE;
      const {nativeWireContracts} = await import(pathToFileURL(root+'/tools/native-wire-contracts.mjs'));
      const {kotlinModels} = await import(pathToFileURL(root+'/tools/wire-contracts.mjs'));
      const canonical = await import(pathToFileURL(source+'/apps/api/src/native/contracts.ts'));
      const require = createRequire(source+'/apps/api/package.json');
      const compilerRequire = createRequire(createRequire(require.resolve('fastify')).resolve('@fastify/ajv-compiler'));
      const Ajv = compilerRequire('ajv/dist/2020.js').default;
      const schemas = await nativeWireContracts(source);
      const ajv = new Ajv({strict:false,validateFormats:false});
      ajv.addSchema({schemas},'pack');
      const validate = ajv.getSchema('pack#/schemas/NativePresentationPage');
      const page = JSON.parse(await readFile(root+'/network/src/test/resources/native-archived-hero-orders.json','utf8'));
      const orders = page.state.orders, hero = orders.heroDeploys[0];
      const withOrders = value => ({...page,state:{...page.state,orders:value}});
      // A future accepted hero need not have a deploy event before an early victory.
      assert.ok(page.events.every(event => event.e !== 'deploy'));
      for (const value of [orders,undefined,{heroDeploys:[]},{heroDeploys:[orders.heroDeploys[1]]}]) {
        const wire = JSON.parse(JSON.stringify(withOrders(value)));
        assert.ok(canonical.NativePresentationPageSchema.safeParse(wire).success);
        assert.ok(validate(wire),JSON.stringify(validate.errors));
        assert.deepEqual(canonical.NativePresentationPageSchema.parse(wire).state.orders,value);
      }
      for (const value of [null,'invalid',{heroDeploys:'invalid'},{heroDeploys:[null]},
          {heroDeploys:[hero,hero,hero]}, {heroDeploys:[{...hero,hero:'future'}]},
          {heroDeploys:[{...hero,tx:0.5}]}, {heroDeploys:[{...hero,tMs:-1}]},
          {heroDeploys:[{...hero,loadout:{...hero.loadout,modifiers:{allied_troop_hp_bps:'600'}}}]}]) {
        const wire = withOrders(value);
        assert.equal(canonical.NativePresentationPageSchema.safeParse(wire).success,false);
        assert.equal(validate(wire),false);
      }
      // Uniqueness is a Zod refinement, not a JSON-schema or Kotlin guarantee.
      assert.equal(canonical.NativePresentationPageSchema.safeParse(withOrders({heroDeploys:[hero,hero]})).success,false);
      const kotlin = kotlinModels('archive-orders-test-fixture',schemas);
      const names = ['NativeClock','NativeCommand','NativePresentationState','NativePresentationPage'];
      const declarations = names.map(name => {
        const marker = '@Serializable\\ndata class '+name+'Dto(';
        assert.ok(kotlin.includes(marker),name);
        return marker+kotlin.split(marker)[1].split('\\n)')[0]+'\\n)\\n';
      });
      // Nested orders stay JsonElement: source schema validates the structure;
      // the generated DTO must preserve it exactly, including optional absence.
      assert.ok(declarations[2].includes('val orders: JsonElement? = null,'));
      const header = '// TEST FIXTURE generated by kotlinModels; exact declarations checked by tools/native-archive-orders-contract.test.mjs.\\n'+
        'package gg.pixelkingdomwars.nativeclient.network.archivewirefixture\\n\\n'+
        'import kotlinx.serialization.Serializable\\nimport kotlinx.serialization.json.JsonElement\\n\\n';
      assert.equal(await readFile(root+'/network/src/test/kotlin/gg/pixelkingdomwars/nativeclient/network/archivewirefixture/NativeArchiveWireFixture.kt','utf8'),header+declarations.join('\\n'));
    `,
  });
  assert.equal(result.status, 0, result.stdout + result.stderr);
});
