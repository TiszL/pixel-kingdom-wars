#!/usr/bin/env bash
#
# Bring up the full production stack locally, with no domain and no TLS.
#
#   ./infra/local-up.sh          # build, migrate, start, verify
#   ./infra/local-up.sh --down   # stop and remove (keeps the data volume)
#   ./infra/local-up.sh --nuke   # …and delete the data volume too
#
# Same images, same worker split, same migration step as a real deploy. What it
# skips is Caddy, because there is no public name to certify. See
# infra/docker-compose.local.yml for why it binds loopback and keeps
# NODE_ENV=production.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

ENV_FILE="infra/.env.local"
COMPOSE="docker compose --env-file $ENV_FILE -f infra/docker-compose.prod.yml -f infra/docker-compose.local.yml"

say() { printf '\n\033[1m▸ %s\033[0m\n' "$*"; }
die() { printf '\n\033[31m  local-up: %s\033[0m\n\n' "$*" >&2; exit 1; }

if [ "${1:-}" = "--down" ] || [ "${1:-}" = "--nuke" ]; then
  [ -f "$ENV_FILE" ] || die "no $ENV_FILE"
  if [ "${1:-}" = "--nuke" ]; then
    $COMPOSE down -v
    echo "  stack down, data volume deleted."
  else
    $COMPOSE down
    echo "  stack down, data kept (--nuke also removes the volume)."
  fi
  exit 0
fi

# --- a local env, generated once -------------------------------------------
# Never reuses infra/.env.prod: a rehearsal must not be one typo away from
# pointing at production keys or a production database.
if [ ! -f "$ENV_FILE" ]; then
  say "creating $ENV_FILE"
  cat > "$ENV_FILE" <<EOF
# Local rehearsal env — generated by infra/local-up.sh. Gitignored.
# Throwaway secrets on purpose: nothing here should ever be reused anywhere.
API_DOMAIN=localhost
API_IMAGE=shardkeep-api:local
POSTGRES_USER=shardkeep
POSTGRES_PASSWORD=$(openssl rand -hex 16)
POSTGRES_DB=shardkeep
JWT_SECRET=$(openssl rand -base64 48 | tr -d '\n')
WEB_ORIGIN=http://localhost:4173
SOLANA_RPC_URL=https://api.devnet.solana.com
DB_POOL_MAX=10
WITHDRAWALS_ENABLED=true
EOF
  echo "  wrote $ENV_FILE with generated secrets."
fi

command -v docker >/dev/null || die "docker is required."

# --- build ------------------------------------------------------------------
# A real git sha, not 'dev'. The service worker names its cache from it, so a
# rehearsal built as 'dev' serves you a stale cache from your last one and you
# spend an hour debugging a bug you already fixed.
SHA="$(git rev-parse --short HEAD 2>/dev/null || echo local)"
say "building shardkeep-api:local ($SHA)"
docker build -q -f apps/api/Dockerfile -t shardkeep-api:local \
  --build-arg "APP_VERSION=$(node -p "require('./package.json').version")-local" \
  --build-arg "GIT_SHA=$SHA" \
  --build-arg "BUILD_TIME=$(date -u +%Y-%m-%dT%H:%M:%SZ)" . >/dev/null

say "starting postgres + redis"
$COMPOSE up -d postgres redis

say "running migrations"
$COMPOSE run --rm --entrypoint sh api -c 'cd /app/apps/api && pnpm db:migrate'

# Caddy deliberately omitted — services are named explicitly.
say "starting api + worker"
$COMPOSE up -d api worker

# --- verify -----------------------------------------------------------------
say "verifying"
for _ in $(seq 1 30); do
  V="$(curl -fsS --max-time 2 http://localhost:8787/version 2>/dev/null || true)"
  [ -n "$V" ] && break
  sleep 2
done
[ -n "$V" ] || { $COMPOSE logs --tail=40 api; die "api never answered on :8787"; }

echo "  /version  $V"
echo "  /health   $(curl -fsS --max-time 5 http://localhost:8787/health || echo FAILED)"

cat <<EOF

  API is up on http://localhost:8787

  Now serve the client against it:

      APP_VERSION=0.1.0-local GIT_SHA=$SHA \\
        VITE_API_URL=http://localhost:8787 \\
        pnpm --filter @shardkeep/web build
      pnpm --filter @shardkeep/web preview   # http://localhost:4173

  Use http://localhost:4173 exactly — not 127.0.0.1, not a LAN IP. CORS is an
  exact-match origin, crypto.randomUUID() (every idempotency key) requires a
  secure context, and Secure cookies are only allowed on localhost among
  insecure origins.

  WHAT THIS DOES NOT TEST — do not go hunting for these:
    - Mobile Wallet Adapter / Seeker wallet connect (needs https + a real device)
    - The TWA shell and Digital Asset Links (needs a public domain)
    - Let's Encrypt issuance and the Caddy layer
    - Cloudflare Pages behaviour, caching and headers

  Stop with:  ./infra/local-up.sh --down
EOF
