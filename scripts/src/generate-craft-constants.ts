/** D153.207: local vehicle policy projection. No build, activation or deployment. */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { PHASE_E_POLICY, PHASE_E_SEEKER_AUCTION, PHASE_E_VEHICLES } from '@shardkeep/shared';

export const CRAFT_CONSTANTS_FILE = resolve(dirname(fileURLToPath(import.meta.url)),
  '../../programs/shardkeep-craft/src/craft_constants.rs');

export function generateCraftConstants(): string {
  const p = PHASE_E_POLICY;
  const rows: ReadonlyArray<readonly [string, 'u64' | 'u16' | 'u8' | 'i64', number]> = [
    ['APPLICATION_FEE_LAMPORTS', 'u64', p.craft.applicationFeeLamports],
    ['CRAFT_OPERATOR_BPS', 'u16', p.craft.operatorBps],
    ['CRAFT_PROJECT_BPS', 'u16', p.craft.projectBps],
    ['BPS_DENOMINATOR', 'u64', p.basisPoints],
    // The common native permit bound in E1 §5 also applies to craft kind3.
    ['MAX_POLICY_PERMIT_TTL_SEC', 'i64', PHASE_E_SEEKER_AUCTION.maxPolicyPermitTtlSec],
    ['VEHICLE_FAMILY_COUNT', 'u8', PHASE_E_VEHICLES.advancedFamilyCount],
    ['VEHICLE_MIN_TIER', 'u8', PHASE_E_VEHICLES.tiers[0]],
    ['VEHICLE_MAX_TIER', 'u8', PHASE_E_VEHICLES.tiers[PHASE_E_VEHICLES.tiers.length - 1]!],
  ];
  if (p.craft.operatorBps + p.craft.projectBps !== p.basisPoints) throw new Error('Craft split must conserve the application fee');
  return '// GENERATED by scripts/src/generate-craft-constants.ts. Do not hand-edit.\n'
    + '// Source: packages/shared/src/constants.ts, E1 §§5/7.1, D153.207.\n'
    + rows.map(([name, type, value]) => {
      if (!Number.isSafeInteger(value) || value < 0 || (type === 'u16' && value > 0xffff) || (type === 'u8' && value > 0xff)) throw new Error(`Invalid shared integer for ${name}`);
      return `pub const ${name}: ${type} = ${value};\n`;
    }).join('');
}

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) throw new Error('Usage: generate-craft-constants.ts [--check]');
  const expected = generateCraftConstants();
  if (args[0] === '--check') {
    if (await readFile(CRAFT_CONSTANTS_FILE, 'utf8') !== expected) throw new Error('Craft constants drift; run the generator');
  } else await writeFile(CRAFT_CONSTANTS_FILE, expected);
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) await main();
