// Synthetic codec vectors, NOT accounts created by a running Core program.
// Run from this checkout: node programs/test-fixtures/charter-core/generate.cjs
// Uses installed lock-resolved raw generated codecs, never the hooked normalizer.
const { createRequire } = require('node:module');
const { readFileSync, writeFileSync } = require('node:fs');
const { resolve, join } = require('node:path');
const { createHash } = require('node:crypto');
const req = createRequire(resolve(__dirname, '../../../packages/chain/package.json'));
const sdk = '@metaplex-foundation/mpl-core';
const load = (path) => req(`${sdk}/dist/src/generated/${path}`);
const { publicKey } = req('@metaplex-foundation/umi');
const { PublicKey } = req('@solana/web3.js');
const pkg = req(`${sdk}/package.json`);
if (pkg.version !== '1.10.0') throw new Error('Re-review codec fixtures before changing the pinned SDK');
const keys = { ASSET: new PublicKey(Buffer.alloc(32, 11)), OWNER: new PublicKey(Buffer.alloc(32, 12)),
  COLLECTION: new PublicKey(Buffer.alloc(32, 13)), COLLECTION_AUTHORITY: new PublicKey(Buffer.alloc(32, 15)) };
const charterId = '12345678-1234-5678-9abc-def012345678';
keys.FREEZE_AUTHORITY = PublicKey.findProgramAddressSync([Buffer.from('charter_freeze'), Buffer.from(charterId.replaceAll('-', ''), 'hex')], new PublicKey(Buffer.alloc(32, 14)))[0];
const pk = (k) => publicKey(k.toBase58());
const paths = ['types/assetV1AccountData', 'types/collectionV1AccountData', 'accounts/pluginHeaderV1',
  'types/pluginRegistryV1AccountData', 'types/plugin', 'types/registryRecord', 'types/basePluginAuthority',
  'types/baseUpdateAuthority', 'types/key', 'types/pluginType', 'types/permanentFreezeDelegate'];
const assetCodec = load(paths[0]).getAssetV1AccountDataSerializer();
const collectionCodec = load(paths[1]).getCollectionV1AccountDataSerializer();
const headerCodec = load(paths[2]).getPluginHeaderV1AccountDataSerializer();
const registryCodec = load(paths[3]).getPluginRegistryV1AccountDataSerializer();
const plugin = load(paths[4]).getPluginSerializer().serialize({ __kind: 'PermanentFreezeDelegate', fields: [{ frozen: true }] });
const name = 'Charter codec fixture', uri = 'https://invalid.example/charter.json';
const base = (seq) => assetCodec.serialize({ key: 1, owner: pk(keys.OWNER),
  updateAuthority: { __kind: 'Collection', fields: [pk(keys.COLLECTION)] }, name, uri, seq });
const asset = (seq) => {
  const data = base(seq), pluginOffset = data.length + headerCodec.fixedSize, registryOffset = pluginOffset + plugin.length;
  const header = headerCodec.serialize({ key: 3, pluginRegistryOffset: BigInt(registryOffset) });
  const registry = registryCodec.serialize({ key: 4, registry: [{ pluginType: 5,
    authority: { __kind: 'Address', address: pk(keys.FREEZE_AUTHORITY) }, offset: BigInt(pluginOffset) }], externalRegistry: [] });
  return Buffer.concat([data, header, plugin, registry]);
};
const vectors = { ASSET_NONE: asset(null), ASSET_SOME: asset(18446744073709551615n),
  COLLECTION_BYTES: Buffer.from(collectionCodec.serialize({ key: 5, updateAuthority: pk(keys.COLLECTION_AUTHORITY),
    name, uri, numMinted: 1, currentSize: 1 })) };
const offsets = { BASE_END: base(null).length, NAME_LENGTH: 66, NAME_START: 70,
  URI_LENGTH: 70 + Buffer.byteLength(name), SEQ_TAG: base(null).length - 1,
  PLUGIN_START: base(null).length + 9, REGISTRY_START: base(null).length + 11 };
const digest = (b) => createHash('sha256').update(b).digest('hex');
const manifest = { provenance: 'SYNTHETIC: raw SDK serialization, no Core execution or chain authority',
  sdk: pkg.version, freezePda: { program: new PublicKey(Buffer.alloc(32, 14)).toBase58(), seed: 'charter_freeze', charterId },
  keys: Object.fromEntries(Object.entries(keys).map(([k,v]) => [k, v.toBase58()])), offsets,
  codecSha256: Object.fromEntries(paths.map(p => [p, digest(readFileSync(req.resolve(`${sdk}/dist/src/generated/${p}`)))])),
  vectorSha256: Object.fromEntries(Object.entries(vectors).map(([k,v]) => [k,digest(v)])) };
const array = (bytes) => `[${Array.from(bytes).join(', ')}]`;
let rust = '// Generated by generate.cjs using raw mpl-core 1.10.0 codecs. SYNTHETIC, not Core execution.\n';
for (const [name,key] of Object.entries(keys)) rust += `pub const ${name}: [u8; 32] = ${array(key.toBytes())};\n`;
for (const [name,bytes] of Object.entries(vectors)) rust += `pub const ${name}: &[u8] = &${array(bytes)};\n`;
for (const [name,n] of Object.entries(offsets)) rust += `pub const ${name}: usize = ${n};\n`;
writeFileSync(join(__dirname, 'vectors.rs'), rust);
writeFileSync(join(__dirname, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
