import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { spawnSync } from 'node:child_process';
import { emittedHeroVocabulary } from './hero-event-contract.mjs';
import { heroCoinReference } from './hero-coin-reference.mjs';

const source = path.resolve(process.env.PKW_NATIVE_SOURCE ?? '.source');
const ts = (await import(pathToFileURL(path.join(source, 'scripts/node_modules/typescript/lib/typescript.js')).href)).default;
const collect = (text) => emittedHeroVocabulary(ts, text);

test('repeated complete coin captures finish in an isolated CI Node process without accumulating import hooks', () => {
  const helper = new URL('./hero-coin-reference.mjs', import.meta.url).href;
  const fixture = new URL('../renderer/src/test/resources/hero/coin-source-reference.json', import.meta.url).href;
  const script = `
    import assert from 'node:assert/strict';
    import {readFile} from 'node:fs/promises';
    import {heroCoinReference} from ${JSON.stringify(helper)};
    const expected=JSON.parse(await readFile(new URL(${JSON.stringify(fixture)}),'utf8'));
    for(let attempt=0;attempt<2;attempt++) assert.deepEqual(await heroCoinReference(${JSON.stringify(source)}),expected);
    process.stdout.write('two-complete-captures');
  `;
  const result=spawnSync(process.execPath,['--input-type=module','-e',script],{encoding:'utf8',timeout:30_000,maxBuffer:1024*1024});
  assert.equal(result.error,undefined,result.error?.message);
  assert.equal(result.status,0,result.stderr);
  assert.equal(result.stdout,'two-complete-captures');
});

test('emitted conditional branches contribute both skills and phases without executing predicates', () => {
  assert.deepEqual(collect(`events.push({ e:'heroSkill', skill: explode() ? 'heads' : (coin ? 'tails' : 'edge'),
    phase: coin ? 'heads' : (other ? 'tails' : 'impact') });`), {
    skills: ['edge', 'heads', 'tails'], phases: ['heads', 'impact', 'tails'],
  });
});
test('only hero event properties contribute vocabulary, including quoted names and repeated emissions', () => {
  assert.deepEqual(collect(`events.push({e:'troopAbility',skill:'notHero',phase:'elsewhere'});
    events.push({'e':'heroSkill','skill':'cast','phase':'impact'});
    events.push({e:'heroSkill',skill:'cast',phase:'impact',note:'notAPhase'});`), {
    skills: ['cast'], phases: ['impact'],
  });
});
test('an opaque emitted branch or missing field fails export instead of silently dropping a live cue', () => {
  for (const expression of ["coin ? 'heads' : runtimeSkill", 'runtimeSkill', "`${skill}Heads`"]) {
    assert.throws(() => collect(`events.push({e:'heroSkill',skill:${expression},phase:'impact'});`), /Unsupported emitted hero skill/);
  }
  assert.throws(() => collect("events.push({e:'heroSkill',skill:'heads',phase:runtimePhase});"), /Unsupported emitted hero phase/);
  assert.throws(() => collect("events.push({e:'heroSkill',skill:'heads'});"), /Expected one emitted hero phase/);
});
test('actual simulator emissions include conditional coin faces and all emitted phase families', async () => {
  const { skills, phases } = collect(await readFile(path.join(source, 'packages/sim/src/sim.ts'), 'utf8'));
  for (const skill of ['doubleOrNothingHeads', 'doubleOrNothingTails']) assert.ok(skills.includes(skill), skill);
  for (const phase of ['heads', 'tails', 'active', 'depart', 'reflect', 'windup', 'impact', 'fakeDeath', 'revive']) assert.ok(phases.includes(phase), phase);
  assert.ok(!skills.includes('doubleOrNothing'), 'shared skill-family names do not replace the two emitted outcomes');
});
test('tracked reference is regenerated byte-for-byte from actual simulator events and web controllers', async () => {
  const expected = JSON.parse(await readFile(new URL('../renderer/src/test/resources/hero/coin-source-reference.json', import.meta.url), 'utf8'));
  const actual = await heroCoinReference(source);
  assert.deepEqual(actual, expected, 'source changes require an explicit reviewed reference refresh');
  for (const value of actual.cases) {
    const coin = value.events.find((event) => event.e === 'heroSkill');
    const deaths = value.events.filter((event) => event.e === 'troopDeath');
    assert.equal(deaths.length, value.face === 'tails' ? 1 : 0);
    if (deaths.length) {
      assert.equal(deaths[0].t, coin.t);
      assert.ok(value.events.indexOf(deaths[0]) > value.events.indexOf(coin), 'the same tick first emits the coin, then lethal death');
    }
    assert.equal(value.bodyAfterDeath, null, 'canonical body death blocks a new skill animation');
    assert.equal(value.sweeps.length, 1, 'coin effect exists even without a living actor');
    assert.ok(value.sweeps[0].frames.every((frame) => frame.startsWith('fx_vex_coinflip_')));
    assert.ok(value.sweeps[0].lifetimeMs > value.sweeps[0].frames.length * value.sweeps[0].stepMs,
      'the coin owns its authored final-frame hold');
    // refundPct stays opaque event metadata; this reference contains no award, balance or recovery state.
    assert.deepEqual(Object.keys(value).sort(), ['body', 'bodyAfterDeath', 'events', 'face', 'input', 'sweeps']);
  }
});
